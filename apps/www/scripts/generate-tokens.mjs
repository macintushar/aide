import { readFileSync, writeFileSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
const monorepo = resolve(root, "..")
const outPath = resolve(root, "www/src/styles/tokens.css")

const AIDE_PROP =
  /^(--n[0-8]|--accent-(subtle|dim|base|hi|fg)|--line(-strong)?|--ok$|--warn$|--danger-base$|--diff-(add|del)-(fg|bg)$|--ease$|--dur-(fast|base|slow|pulse)$|--radius$)/

function parseBlocks(css) {
  const dark = css.match(/:root,\s*\.dark\s*\{([^}]*)\}/)?.[1] ?? ""
  const light = css.match(/\.light\s*\{([^}]*)\}/)?.[1] ?? ""
  const pick = (block) =>
    block
      .split(";")
      .map((line) => line.trim())
      .filter((line) => AIDE_PROP.test(line.split(":")[0].trim()))
      .map((line) => `  ${line};`)
      .join("\n")
  return { dark: pick(dark), light: pick(light) }
}

function fail(why) {
  console.error(`generate-tokens: ${why}`)
  process.exit(1)
}

const globalsPath = resolve(monorepo, "packages/ui/src/styles/globals.css")
const globalsCss = readFileSync(globalsPath, "utf8")
let source = `packages/ui/src/styles/globals.css`
let parsed = parseBlocks(globalsCss)

if (!parsed.dark || !parsed.light) {
  const designPath = resolve(monorepo, "docs/DESIGN.md")
  const design = readFileSync(designPath, "utf8")
  const cssFence =
    design
      .split(/```css\n/)
      .map((chunk) => chunk.split("```")[0])
      .find(
        (chunk) =>
          chunk.includes("--aide primitives") || chunk.includes("--n0:")
      ) ?? ""
  if (!cssFence) {
    fail(
      `no aide primitives found in packages/ui globals.css or docs/DESIGN.md — run the §11.2 migration or restore the §11.1 block`
    )
  }
  parsed = parseBlocks(cssFence)
  source = `docs/DESIGN.md §11.1 (packages/ui globals.css not yet migrated)`
}

if (!parsed.dark || !parsed.light)
  fail("incomplete aide token blocks in source")

const banner = `/* Generated by scripts/generate-tokens.mjs from ${source}. Do not edit. */`

const css = `${banner}

:root,
.dark {
${parsed.dark}
}

.light {
${parsed.light}
}

@media (prefers-color-scheme: light) {
  :root {
${parsed.light.replace(/\n  /g, "\n    ")}
  }
}

/* Starlight writes data-theme on <html>; these win over the media query
   above so the docs theme toggle drives the aide tokens too. */
[data-theme="dark"] {
${parsed.dark}
}

[data-theme="light"] {
${parsed.light}
}
`

writeFileSync(outPath, css)
console.log(`generate-tokens: wrote src/styles/tokens.css from ${source}`)
